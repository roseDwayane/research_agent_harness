#!/usr/bin/env python3
"""Snapshot the legacy Unit registry (``ideate_units.json``) into ``contracts/legacy_snapshot.json``.

The legacy ai-scientist-ideate skill keeps one card per Unit in ``scripts/ideate_units.json``; that file stays the
source of truth for *implementation facts* (what each Unit reads, owns, checks, and how it fails). The v2 contracts
(``contracts/architecture.json``) hold only what v2 decides. This script copies the implementation facts into a
hash-pinned snapshot so that the v2 documentation and validators work without the legacy checkout, and so that
drift between the two is detectable (``--check``).

    python scripts/import_legacy_registry.py --legacy-registry <path>/ideate_units.json
    python scripts/import_legacy_registry.py --check              # exit 1 when the live registry differs
    IDEATE_LEGACY_SKILL_DIR=<legacy skill dir> python scripts/import_legacy_registry.py

Exit codes: 0 ok / in sync, 1 drift (``--check``), 2 usage or I/O error.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

MODULE_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = MODULE_ROOT / "contracts" / "legacy_snapshot.json"

# Card fields copied verbatim. Everything else on a legacy card (the twelve-condition `achieved` evidence prose,
# fork bookkeeping) is summarised as `achieved_level` / `conditions_met` instead.
FIELDS = [
    "block", "purpose", "rules", "instance", "when", "reads", "requires", "forbidden", "frozen", "owns", "revises",
    "revised_by", "schemas", "actor", "network", "budget", "scratch", "done_when", "judgement_fields", "computed_by",
    "failures", "degraded", "hard_stop", "resume", "tests", "counts", "status_line", "audit", "decisions",
    "provenance", "override", "invalidates", "code", "server", "io",
]
# The maturity levels of the legacy `it_units.py` (LEVELS): a level is achieved when its conditions and every lower
# level's conditions are met.
LEVELS = [("L1", [1, 2, 3, 4]), ("L2", [5, 6, 10]), ("L3", [7, 8, 9]), ("L4", [11, 12])]


def achieved_level(card: dict) -> tuple[str, int]:
    achieved = card.get("achieved") or {}
    met = {int(k) for k, v in achieved.items() if isinstance(v, dict) and v.get("status") == "yes"}
    level = "L0"
    for name, conds in LEVELS:
        if all(c in met for c in conds):
            level = name
        else:
            break
    return level, len(met)


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build_snapshot(registry_path: Path) -> dict:
    raw = registry_path.read_bytes()
    reg = json.loads(raw.decode("utf-8"))
    if reg.get("schema") != "ideate-units/1":
        raise ValueError(f"{registry_path}: expected schema ideate-units/1, found {reg.get('schema')!r}")
    units = {}
    for card in reg.get("units") or []:
        level, met = achieved_level(card)
        entry = {k: card[k] for k in FIELDS if k in card}
        entry["achieved_level"] = level
        entry["conditions_met"] = met
        units[card["id"]] = entry
    return {
        "schema": "ideate-legacy-snapshot/1",
        "note": "Generated by scripts/import_legacy_registry.py from the legacy ideate_units.json - do not edit by hand.",
        "source": {"file": "ideate_units.json", "schema": reg.get("schema"), "sha256": sha256_bytes(raw)},
        "imported_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "infrastructure": reg.get("infrastructure") or {},
        "units": units,
    }


def locate(arg: str | None) -> Path | None:
    if arg:
        return Path(arg)
    skill_dir = os.environ.get("IDEATE_LEGACY_SKILL_DIR")
    return Path(skill_dir or MODULE_ROOT) / "scripts" / "ideate_units.json"   # default: this module's own registry


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):        # a console code page (cp1252) must not crash on a path
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(errors="backslashreplace")
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--legacy-registry", help="path to the legacy ideate_units.json (or set IDEATE_LEGACY_SKILL_DIR)")
    ap.add_argument("--out", default=str(DEFAULT_OUT), help="snapshot path (default: contracts/legacy_snapshot.json)")
    ap.add_argument("--check", action="store_true", help="compare only; exit 1 when the snapshot is out of date")
    a = ap.parse_args(argv)

    src = locate(a.legacy_registry)
    if src is None:
        print("error: no legacy registry given (--legacy-registry or IDEATE_LEGACY_SKILL_DIR)", file=sys.stderr)
        return 2
    if not src.is_file():
        print(f"error: legacy registry not found: {src}", file=sys.stderr)
        return 2
    try:
        new = build_snapshot(src)
    except (OSError, ValueError, json.JSONDecodeError) as e:
        print(f"error: cannot read the legacy registry: {e}", file=sys.stderr)
        return 2

    out = Path(a.out)
    if a.check:
        if not out.is_file():
            print(f"DRIFT: no snapshot at {out}")
            return 1
        old = json.loads(out.read_text(encoding="utf-8"))
        if old.get("source", {}).get("sha256") == new["source"]["sha256"]:
            print(f"in sync: snapshot matches {src} (sha256 {new['source']['sha256'][:12]})")
            return 0
        added = sorted(set(new["units"]) - set(old.get("units") or {}))
        removed = sorted(set(old.get("units") or {}) - set(new["units"]))
        changed = sorted(u for u in set(new["units"]) & set(old.get("units") or {})
                         if new["units"][u] != {**old["units"][u]})
        print(f"DRIFT: legacy registry changed (sha256 {old.get('source', {}).get('sha256', '?')[:12]} -> "
              f"{new['source']['sha256'][:12]}); units added {added or '-'}, removed {removed or '-'}, "
              f"changed {changed or '-'}. Re-run without --check to refresh the snapshot.")
        return 1

    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(".json.tmp")
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        json.dump(new, f, indent=1, ensure_ascii=False)
        f.write("\n")
    os.replace(tmp, out)
    print(f"wrote {out} ({len(new['units'])} units, source sha256 {new['source']['sha256'][:12]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
